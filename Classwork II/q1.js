// Destructuring Array
const numbers = [10, 20, 30, 40, 50]
const [a,b,c,d,e] = numbers  

console.log(a)
console.log(b)
console.log(c)
console.log(d)
console.log(e)  

// Destructuring Object
const person = {
    name: 'Rahul',
    age: "18",
    gender: "Male"
}

const {name, age, gender} = person
console.log(name)
console.log(age)
console.log(gender)




